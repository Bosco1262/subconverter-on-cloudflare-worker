// Copies required base/ assets from the upstream repo into src/embed/ as an embedded VFS module.
// Usage: npm run sync-base [-- --upstream <path>]

import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, relative, posix } from "node:path";

const args = process.argv.slice(2);
let upstreamIdx = args.indexOf("--upstream");
const upstreamDir = upstreamIdx !== -1 && args[upstreamIdx + 1] ? args[upstreamIdx + 1] : join(process.cwd(), "..", "..", "subconverter");
const baseDir = join(upstreamDir, "base");
const outDir = join(process.cwd(), "src", "embed");
const outFile = join(outDir, "files.ts");

if (!existsSync(baseDir)) {
  console.error(`upstream base directory not found: ${baseDir}`);
  process.exit(1);
}
mkdirSync(outDir, { recursive: true });

const files: Record<string, string> = {};

function walk(dir: string, prefix: string): void {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    const rel = prefix ? posix.join(prefix, entry.name) : entry.name;
    if (entry.isDirectory()) {
      walk(full, rel);
    } else {
      if (entry.name === "generate.ini" || entry.name === "gistconf.ini") continue;
      const content = readFileSync(full, "utf8");
      files[rel] = content;
    }
  }
}

walk(baseDir, "");

const lines: string[] = ["// AUTO-GENERATED by scripts/sync-base.ts — do not edit", "", "export const EMBEDDED_FILES: Record<string, string> = {"];
for (const [path, content] of Object.entries(files).sort(([a], [b]) => (a < b ? -1 : 1))) {
  lines.push(`  ${JSON.stringify(path)}: ${JSON.stringify(content)},`);
}
lines.push("};", "");
lines.push(`export const EMBEDDED_FILE_COUNT = ${Object.keys(files).length};`, "");

writeFileSync(outFile, lines.join("\n"), "utf8");
console.log(`embedded ${Object.keys(files).length} files (${(JSON.stringify(files).length / 1024).toFixed(0)} KB) -> src/embed/files.ts`);
void relative;
